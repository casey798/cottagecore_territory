export type DecorationPackCategory = 'furniture' | 'aesthetics' | 'nature';

export interface DecorationAsset {
  assetId: string;
  name: string;
  category: DecorationPackCategory;
  imageKey: string;       // relative path under src/assets/, resolved at render time
  gridW: number;          // 1 or 2
  gridH: number;          // 1 or 2
}

export interface AssetPack {
  category: DecorationPackCategory;
  displayName: string;
  icon: string;
  assets: DecorationAsset[];
}

